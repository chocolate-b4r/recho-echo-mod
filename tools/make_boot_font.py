#!/usr/bin/env python3
"""Extract the boot screen's characters from RECHO's large font into patches/boot_font.h.

    py -3 -I tools/make_boot_font.py RECHO-0.10.1.IMG > patches/boot_font.h

The boot screen is drawn at ~0.17 s, before RECHO loads its fonts (~0.20 s, "font: bitmap
fonts" in the log). With no font loaded, draw_text falls back to the bold 6 x 11 boot font.
So the hooks carry the few glyphs they need, copied from the large font (font B, image part 1:
33 bytes per code point = 16 rows of 16 bits, MSB = left pixel, then 0x80 | advance). This is
the font RECHO draws "Power off" in.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rkimg import parts  # noqa: E402

TEXT = ("> init", "> boot", "> loading kernel...", "> compiling data...", "> applying interface...",
        "> system ready", "[", "] 100%> mounting /dev/cho4e...", "login: 0.10.1")
GLYPH = 33


def main():
    d = open(sys.argv[1], "rb").read()
    _, ps = parts(d)
    off, _size = ps[1]
    chars = sorted(set("".join(TEXT)))
    rows = {}
    for ch in chars:
        g = d[off + ord(ch) * GLYPH: off + (ord(ch) + 1) * GLYPH]
        rows[ch] = ([(g[2 * r] << 8) | g[2 * r + 1] for r in range(16)], g[32] & 0x7F or 4)
    used = [r for r in range(16) if any(rows[c][0][r] for c in chars)]
    top, bot = min(used), max(used)
    out = ["/* generated by tools/make_boot_font.py from RECHO's large font (image part 1) */",
           "#define BF_TOP %d" % top, "#define BF_H %d" % (bot - top + 1),
           'static const char BF_MAP[] = "%s";' % "".join(chars).replace("\\", "\\\\").replace('"', '\\"'),
           "static const unsigned char BF_ADV[%d] = {%s};" % (len(chars), ", ".join(str(rows[c][1]) for c in chars)),
           "static const unsigned short BF_ROWS[%d][BF_H] = {" % len(chars)]
    for c in chars:
        out.append("    {%s},  /* %r */" % (", ".join("0x%04X" % v for v in rows[c][0][top:bot + 1]), c))
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
